/**
 * @fileOverview 清点"谁真的在消费 chat 流"，而不是"谁的文件里出现过这个字符串"
 * @module evals/platform-probes/enumerate-stream-consumers
 * @description
 * v1.34 我把消费方数成 6 处，靠的是对 `core/chat/stream` 的字符串检索。
 * 那是错的计数法：**生成出来的 API 封装里出现过端点名，不等于有人在消费它**。
 * `xxzx.app.console` 就是反例——`services/llm-base/llm.ts:6 postCoreChatStream` 是 Swagger 生成的，
 * 全仓**零调用者**，也没有任何 event-stream/XRequest/fetchEventSource 的使用。
 *
 * 所以这条脚本把两级判据分开：
 *  1) 端点名出现在哪些文件（原始命中）
 *  2) 那个符号/端点有没有**调用者**，以及有没有真的流式读取手段
 * 只有 2 过了才算消费方。输出直接给出"几端会画错、几端不读、几处是生成的死封装"。
 *
 * 用法（在 `src/` 下）：
 *   node evals/platform-probes/enumerate-stream-consumers.mjs [仓库根目录] [--out=结果文件]
 */
import fs from 'node:fs'
import path from 'node:path'

/**
 * 位置参数只取"不以 -- 开头的那一个"。
 * 上一版直接拿 argv[2]，于是 `--out=...` 被当成 ROOT，脚本去 scandir 那个字符串，
 * 报 ENOENT —— 症状长得像"扫描失败"，其实是参数解析把自己喂错了。
 */
const POSITIONAL = process.argv.slice(2).filter(a => !a.startsWith('--'))
const ROOT = POSITIONAL[0] || 'D:/workspace/xxzx'
const STREAM_EP = 'core/chat/stream'
/** 真的流式读取手段：命中这些才算"在解析 SSE" */
const SSE_MARKERS = [/text\/event-stream/, /XRequest/, /fetchEventSource/, /useXChat/, /EventSource/, /split\(\/\\r\?\\n\\r\?\\n\//, /collectSse/]
/** 生成代码的常见标记：这些文件不能当"有人在用"的证据 */
const GENERATED_HINTS = [/@ts-ignore[\s\S]{0,80}eslint-disable/, /Generated by the swagger code generator/, /eslint-disable[\s\S]{0,40}@ts-ignore/]

/**
 * @description 递归收集源文件
 * @param {String} dir 目录
 * @param {String[]} out 累加器
 * @returns {String[]} 文件列表
 */
function walk(dir, out = []) {
    let ents
    try {
        ents = fs.readdirSync(dir, {withFileTypes: true})
    } catch (e) {
        return out
    }
    for (const e of ents) {
        if (e.name === 'node_modules' || e.name === '.git' || e.name === 'dist' || e.name === 'build') {
            continue
        }
        const p = path.join(dir, e.name)
        if (e.isDirectory()) {
            walk(p, out)
        } else if (/\.(ts|tsx|js|jsx|vue)$/.test(e.name)) {
            out.push(p)
        }
    }
    return out
}

/**
 * 装置必须通电：ROOT 读不到就直接失败退出。
 * 否则"扫描根写错"会表现成 0 条命中，很容易被读成"没有消费方"——那是假结论。
 */
if (!fs.existsSync(ROOT) || !fs.statSync(ROOT).isDirectory()) {
    console.error(`[enumerate-stream-consumers] 扫描根不存在或不是目录: ${ROOT}`)
    process.exit(2)
}
const repos = fs.readdirSync(ROOT, {withFileTypes: true}).filter(d => d.isDirectory()).map(d => d.name)
if (!repos.length) {
    console.error(`[enumerate-stream-consumers] 扫描根下没有任何仓库目录: ${ROOT}`)
    process.exit(2)
}
const rows = []
for (const repo of repos) {
    const srcDir = path.join(ROOT, repo, 'src')
    if (!fs.existsSync(srcDir)) {
        continue
    }
    const files = walk(srcDir)
    const hits = []
    for (const f of files) {
        let text
        try {
            text = fs.readFileSync(f, 'utf8')
        } catch (e) {
            continue
        }
        if (!text.includes(STREAM_EP)) {
            continue
        }
        const isGenerated = GENERATED_HINTS.some(re => re.test(text))
        /** 抽出端点所在的函数名，再回文件里数它被调用的次数（定义处不算） */
        const fnNames = [...text.matchAll(/(?:export\s+)?async function (\w+)[^]{0,400}?"?\/?`?"?[\s\S]{0,200}core\/chat\/stream/g)].map(m => m[1])
        let callers = 0
        for (const name of fnNames.length ? fnNames : []) {
            const all = text.match(new RegExp(`\\b${name}\\s*\\(`, 'g')) || []
            callers += Math.max(0, all.length - 1)
            /** 同文件之外也要算 */
            for (const g of files) {
                if (g === f) {
                    continue
                }
                const gt = fs.readFileSync(g, 'utf8')
                if (new RegExp(`\\b${name}\\s*\\(`).test(gt)) {
                    callers++
                }
            }
        }
        const sseMarkers = SSE_MARKERS.filter(re => re.test(text)).map(re => String(re).slice(1, -1))
        hits.push({
            自身: repo === 'xxzx.llm.api',
            有具名封装: fnNames.length > 0,
            文件: path.relative(path.join(ROOT, repo), f),
            生成代码: isGenerated,
            封装函数: fnNames,
            调用者数: fnNames.length ? callers : 'n/a（没有具名封装）',
            流式解析证据: sseMarkers,
        })
    }
    if (hits.length) {
        rows.push({repo, hits})
    }
}

/**
 * 分类：真消费方 = 有流式解析证据，或（不是生成代码且有调用者）
 * @param {Object} h 单条命中
 * @returns {String} 分类
 */
function classify(h) {
    /**
     * 提供方自己不算消费方：llm.api 里的命中都是注释或自述
     * （如 memory/api.js 那句"与 /core/chat/stream 一致"），算进去会虚增数量。
     */
    if (h.自身) {
        return '提供方自身（不算消费方）'
    }
    /**
     * 零调用者优先于"有解析证据"：console 与 pdfviewer 各有一个 services/llm/chat.ts 的
     * execChat（里面是裸 fetch），**全仓零调用者** —— 有 fetch 却没调用者，仍是死封装。
     * 上一版把"有 SSE 标记"排在前面，会把这类判成消费方；顺序本身就是这个 bug。
     */
    if (h.有具名封装 && Number(h.调用者数) === 0) {
        return '不算消费方（零调用者的封装' + (h.生成代码 ? '，生成代码' : '') + '）'
    }
    if (h.流式解析证据.length) {
        return '真消费方（有 SSE 解析证据且有调用者）'
    }
    return '待人工判定'
}

const flat = []
for (const r of rows) {
    for (const h of r.hits) {
        flat.push({仓库: r.repo, ...h, 分类: classify(h)})
    }
}
const 真 = flat.filter(x => x.分类.startsWith('真消费方'))
const 死封装 = flat.filter(x => x.分类.startsWith('不算'))
const 自身 = flat.filter(x => x.分类.startsWith('提供方'))
const 待判 = flat.filter(x => x.分类.startsWith('待'))

/**
 * 自己写 JSONL/JSON，不用 shell 重定向：
 * PowerShell 的 `*>` 会把 UTF-8 输出按控制台代码页转一道，中文键名直接烂掉，
 * 读回来 JSON.parse 全失败（本轮已因此差点把"没有结论"读成"结论是空"）。
 */
const OUT = (process.argv.find(a => a.startsWith('--out=')) || '').split('=').slice(1).join('=')

/**
 * @description 落文件并打印
 * @param {Object} obj 结果
 */
function emit(obj) {
    const text = JSON.stringify(obj, null, 1)
    if (OUT) {
        fs.writeFileSync(OUT, text)
    }
    console.log(text)
}

emit({
    扫描根: ROOT,
    原始命中处: flat.length,
    真消费方数: 真.length,
    真消费方: 真.map(x => `${x.仓库}/${x.文件}`),
    不算消费方: 死封装.map(x => `${x.仓库}/${x.文件}（${x.封装函数.join(',')} 调用者 ${x.调用者数}）`),
    提供方自身: 自身.map(x => `${x.仓库}/${x.文件}`),
    待人工判定: 待判.map(x => `${x.仓库}/${x.文件}`),
    读我: '原始命中数不等于消费方数。v1.34 那句"消费方有 6 处"是错的：'
        + 'app.console 与 pdfviewer 的 llm-base/llm.ts 都是 Swagger 生成封装、零调用者，'
        + 'console 与 pdfviewer 的 services/llm/chat.ts 里那个 execChat（裸 fetch）同样全仓零调用者。'
        + '按"有 SSE 解析证据**且有调用者**"算，真消费方是 ' + 真.length + ' 处。',
})
process.exit(待判.length ? 1 : 0)
